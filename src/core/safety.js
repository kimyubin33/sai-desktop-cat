// 긴급한 위험 신호를 감지하면 평소 흐름(정리·공유)을 멈추고 안전 확인을 먼저 한다.
// 일상적인 과장 표현("힘들어 죽겠다")은 위험 신호로 보지 않는다.

const SELF_RISK = [
  /죽고\s*싶/, /자살/, /자해/, /살기\s*싫/, /사라지고\s*싶/, /없어지고\s*싶/, /목숨을?\s*끊/, /끝내고\s*싶[다어].*(삶|인생|모든\s*걸|다)/,
];

const OTHER_RISK = [/죽여\s*버리/, /죽이고\s*싶/, /때리고\s*싶/, /해치고\s*싶/, /칼로/, /패\s*버리고\s*싶/];

function checkSafety(text) {
  const t = text || '';
  if (SELF_RISK.some((r) => r.test(t))) return 'self';
  if (OTHER_RISK.some((r) => r.test(t))) return 'others';
  return null;
}

